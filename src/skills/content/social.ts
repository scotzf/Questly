import type { Level, Skill } from "../types";
const lvl = (
  id: string,
  name: string,
  goal: string,
  weeks: number,
  milestones: { id: string; title: string; n?: number; unit?: string }[],
  practice: { id: string; title: string; minutes?: number; perWeek?: number }[],
  tips: string[],
  mistakes: string[],
): Level => ({
  id,
  name,
  goal,
  weeks,
  milestones: milestones.map((m) => ({
    id: m.id,
    title: m.title,
    verify: m.n ? ("count" as const) : ("self" as const),
    ...(m.n ? { target: { amount: m.n, unit: m.unit ?? "times" } } : {}),
  })),
  practice: practice.map((p) => ({
    id: p.id,
    title: p.title,
    kind: p.perWeek ? ("habit" as const) : ("task" as const),
    ...(p.minutes ? { minutes: p.minutes } : {}),
    ...(p.perWeek ? { perWeek: p.perWeek } : {}),
  })),
  tips,
  mistakes,
});
